const rollback = `-- Logical rollback only: no physical DELETE and no predecessor mutation.
begin;
select pg_advisory_xact_lock(hashtext('fitmatch_taxonomy:${newPolicy}'));
do $$
begin
  if not exists (select 1 from fitmatch_taxonomy.policy_versions where code='${newPolicy}') then
    raise exception 'Policy ${newPolicy} does not exist';
  end if;
  if not exists (select 1 from fitmatch_taxonomy.policy_versions where code='${basePolicy}' and status='validated') then
    raise exception 'Validated predecessor policy is unavailable';
  end if;
end $$;
update fitmatch_taxonomy.promotion_manifests
set status='rolled_back', validation_result=coalesce(validation_result,'{}'::jsonb) || '{"logical_rollback":true,"physical_delete":false}'::jsonb
where policy_version='${newPolicy}' and status <> 'rolled_back';
update fitmatch_taxonomy.policy_versions set status='rolled_back' where code='${newPolicy}';
commit;
`;

